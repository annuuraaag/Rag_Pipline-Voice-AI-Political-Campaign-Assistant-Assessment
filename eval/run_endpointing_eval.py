"""End-of-turn detection: how long does a finished question wait, and how often would a
mid-sentence pause end the turn too early?

    python eval/run_endpointing_eval.py [--fixed-ms 900]

Every query in eval/queries.jsonl is turned into what a browser recogniser delivers (lower case,
no punctuation) and assessed word by word, with its `history` turns as conversation memory:

  * the full question is the end of the turn: its wait is pure latency (lower is better);
  * every shorter prefix is a point where the user has NOT finished: if they paused there for
    longer than the wait, the turn would end early and the question would be cut off.

Compared with the fixed timeout the web app used before (--fixed-ms). Needs no models and no
API key; the rules are deterministic. Results: eval/results/endpointing_eval.{json,md}.
"""
from __future__ import annotations

import argparse
import json
import re
import statistics
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
import sys  # noqa: E402

sys.path.insert(0, str(ROOT / "backend"))

from app.conversation.state import ConversationState  # noqa: E402
from app.conversation.understanding import understand  # noqa: E402
from app.voice.endpointing import Endpointer  # noqa: E402

PAUSES_MS = [300, 500, 700, 900, 1200]


def as_heard(text: str) -> str:
    """What Chrome's recogniser returns: lower case, no punctuation."""
    return " ".join(re.findall(r"[a-z0-9']+", text.lower()))


def memory(history: list[str]) -> ConversationState | None:
    if not history:
        return None
    st = ConversationState("eval")
    for h in history:
        st.observe_user(understand(h), h)
    return st


def evaluate(queries: list[dict], e: Endpointer, fixed_ms: int) -> dict:
    finals, prefixes, rows = [], [], []
    for q in queries:
        st = memory(q.get("history", []))
        words = as_heard(q["query"]).split()
        verdicts = [e.assess(" ".join(words[:i]), st) for i in range(1, len(words) + 1)]
        final = verdicts[-1]
        finals.append(final)
        prefixes.extend(verdicts[:-1])
        rows.append({"id": q["id"], "type": q["type"], "heard": " ".join(words), "turn": final.turn,
                     "wait_ms": final.wait_ms, "reason": final.reason,
                     "early_points_500ms": sum(v.wait_ms <= 500 for v in verdicts[:-1]),
                     "trace": " ".join(f"{w}:{v.turn[0].upper()}" for w, v in zip(words, verdicts, strict=True))})
    waits = [f.wait_ms for f in finals]

    def exposure(verdicts, pause):
        return round(sum(v.wait_ms <= pause for v in verdicts) / len(verdicts), 3)
    return {
        "queries": len(queries),
        "fixed_ms": fixed_ms,
        "waits_ms": e.waits,
        "final": {
            "turns": dict(Counter(f.turn for f in finals)),
            "adaptive_wait_ms": {"mean": round(statistics.fmean(waits), 1), "p50": statistics.median(waits),
                                 "max": max(waits)},
            "fixed_wait_ms": fixed_ms,
            "saved_ms_mean": round(fixed_ms - statistics.fmean(waits), 1),
            "finished_questions_waiting_longer_than_fixed": sum(w > fixed_ms for w in waits),
        },
        "prefixes": {
            "n": len(prefixes),
            "turns": dict(Counter(p.turn for p in prefixes)),
            # Share of mid-question points where a pause of this length ends the turn early.
            "early_end_if_paused_ms": {
                str(p): {"adaptive": exposure(prefixes, p), "fixed": 1.0 if p >= fixed_ms else 0.0} for p in PAUSES_MS
            },
            "protected_beyond_fixed": round(sum(v.wait_ms > fixed_ms for v in prefixes) / len(prefixes), 3),
        },
        "rows": rows,
    }


def markdown(r: dict) -> str:
    f, p, w = r["final"], r["prefixes"], r["waits_ms"]
    lines = [
        "# End-of-turn detection", "",
        "Generated by `eval/run_endpointing_eval.py`; do not edit by hand. "
        f"{r['queries']} questions from `eval/queries.jsonl`, as a browser recogniser delivers them "
        "(lower case, no punctuation), assessed word by word with their conversation history.", "",
        f"Waits: complete {w['complete']} ms · likely {w['likely']} ms · unsure {w['unsure']} ms · "
        f"incomplete {w['incomplete']} ms. Baseline: a fixed {r['fixed_ms']} ms after the last word.", "",
        "## Finished questions (wait = latency)", "",
        "| Policy | mean wait | p50 | max |", "|---|---|---|---|",
        f"| Fixed | {r['fixed_ms']} ms | {r['fixed_ms']} ms | {r['fixed_ms']} ms |",
        f"| Adaptive | {f['adaptive_wait_ms']['mean']} ms | {f['adaptive_wait_ms']['p50']} ms | {f['adaptive_wait_ms']['max']} ms |",
        "", f"Verdicts on the finished questions: {f['turns']}. Mean saving per question: **{f['saved_ms_mean']} ms**; "
        f"finished questions that now wait longer than before: {f['finished_questions_waiting_longer_than_fixed']}.", "",
        f"## Unfinished questions ({p['n']} mid-question points)", "",
        "Share of points where a pause of the given length would end the turn before the user finished:", "",
        "| Pause | Adaptive | Fixed |", "|---|---|---|",
    ]
    for pause, v in p["early_end_if_paused_ms"].items():
        lines.append(f"| {pause} ms | {v['adaptive']:.0%} | {v['fixed']:.0%} |")
    lines += [
        "", f"Verdicts mid-question: {p['turns']}. **{p['protected_beyond_fixed']:.0%}** of mid-question points "
        f"(after 'for', 'the', 'um', …) now wait longer than the fixed {r['fixed_ms']} ms, so a hesitation there no "
        "longer cuts the question off.", "",
        "Reading the trade-off: a finished question is answered sooner, and pauses after words that need a "
        "continuation are safer than before. The cost: a pause longer than 300–550 ms right after a phrase that "
        "already sounds complete (\"…propose\", \"…for Guntur\" before \"and Visakhapatnam\") now ends the turn. "
        "The design bets that people hesitate after \"for\", \"the\" or \"um\" more often than after a complete "
        "phrase; real usage logs should confirm it. Turning the setting off restores the fixed pause.", "",
        "## Per question", "",
        "| id | heard | verdict | wait | why | trace (C/L/U/I per word) |", "|---|---|---|---|---|---|",
    ]
    for row in r["rows"]:
        lines.append(f"| {row['id']} | {row['heard']} | {row['turn']} | {row['wait_ms']} | {row['reason']} | {row['trace']} |")
    return "\n".join(lines) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--queries", default=str(ROOT / "eval" / "queries.jsonl"))
    ap.add_argument("--fixed-ms", type=int, default=900, help="the fixed end-of-utterance timeout to compare with")
    ap.add_argument("--out", default=str(ROOT / "eval" / "results"))
    args = ap.parse_args()
    queries = [json.loads(line) for line in Path(args.queries).read_text(encoding="utf-8").splitlines() if line.strip()]
    report = evaluate(queries, Endpointer(), args.fixed_ms)
    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)
    (out / "endpointing_eval.json").write_text(json.dumps(report, indent=2), encoding="utf-8")
    md = markdown(report)
    (out / "endpointing_eval.md").write_text(md, encoding="utf-8")
    print(md.split("## Per question")[0])
    print(f"wrote {out / 'endpointing_eval.md'}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
